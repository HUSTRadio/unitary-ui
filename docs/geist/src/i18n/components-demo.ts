export function demoTextWithValues(
  language: DocsLanguage,
  source: string,
  values: Record<string, string | number>,
): string {
  return Object.entries(values).reduce(
    (text, [key, value]) => text.replaceAll(`{${key}}`, String(value)),
    demoText(language, source),
  );
}
