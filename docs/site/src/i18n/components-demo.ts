export function demoSectionTitle(language: DocsLanguage, source: string): string {
  const words = source.split("-");
  const sentenceCase = words
    .join(" ")
    .replace(/^./u, (first) => first.toUpperCase());
  const titleCase = words
    .map((word) => word.replace(/^./u, (first) => first.toUpperCase()))
    .join(" ");
  const catalogKey = [source, sentenceCase, titleCase].find(
    (candidate) => DEMO_COPY["zh-CN"][candidate] !== undefined,
  );

  return demoText(language, catalogKey ?? sentenceCase);
}

export function demoTextWithValues(
  language: DocsLanguage,
  source: string,
  values: Record<string, string | number>,
): string {
  return Object.entries(values).reduce(
    (text, [key, value]) => text.replaceAll(`{${key}}`, String(value)),
    demoText(language, source),
  );
}
